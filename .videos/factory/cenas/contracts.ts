export const queueRoot = 'assets/cenas/tarefas';
export const states = ['001-afazer', '002-desenvolvendo', '003-gerados'] as const;
export type State = typeof states[number];
export type Task = { key: string; state: State; path: string };
export type Rect = { x: number; y: number; width: number; height: number };
export type Background = { asset: string; type: 'video' | 'image'; timing?: 'global' | 'scene' };
export type Pose = { at: number; asset: string; width: number; anchorX: number; anchorY: number };
export type Item = { id: string; asset: string; x: number; ground: number; width: number; at: number;
  entrance?: number; entranceOffset?: number; initiallyVisible?: boolean; until?: number; exit?: number; anchorY?: number; layer?: 'front' | 'back'; shadow?: boolean;
  clip?: Rect; occlusion?: Rect };
export type Title = { at: number; lines: string[]; x?: number; y?: number; fontSize?: number };
export type Scene = { id: string; from: number; to: number; background: Background;
  objectFocus?: boolean;
  checklist?: { heading: string; lines: string[] };
  preparation?: 'rice' | 'eggs' | 'sauce' | 'ready' | 'egg-colors';
  cooking?: {stage:'preview'|'saute'|'garlic'|'tomato'|'wells'|'add-eggs'|'cook'|'lid'|'serve';table?:boolean};
  character?: { faceX: number; faceY: number; poses: Pose[] };
  items: Item[]; titles: Title[]; transition?: 'cut' | 'fade' };
export type Plan = { schemaVersion: 1; narration: string; audio: string; font: string;
  audioTrimEndSeconds?: number;
  holdSeconds: number; scenes: Scene[];
  voice?: { provider: 'elevenlabs'; fingerprint: string; audioHash: string };
  output?: { file: string; hash: string; signature: string } };
export type AssetInfo = { width: number; height: number; seconds?: number };
export type RuntimeScene = Scene & { fromFrame: number; durationInFrames: number; backgroundRate: number };
export type ThemeProps = { scenes: RuntimeScene[]; audio: string; font: string;
  audioEndAt?: number;
  durationInFrames: number; media: Record<string, AssetInfo> };
export type Work = { id: string; key: string; pending?: string; blocked?: string;
  run?: { signature: string; file: string; hash?: string; complete: boolean };
  promotion?: { source: string; output: NonNullable<Plan['output']> };
  speechRequest?: { fingerprint: string; status: 'requesting' | 'uncertain' } };
export const emptyThemeProps: ThemeProps = { scenes: [], audio: '', font: '', durationInFrames: 30, media: {} };
